// Downloads the exact woff2 subsets used by the app and writes a local @font-face sheet.
// Keeps the app fully offline: no runtime request ever leaves the machine.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fontDir = path.join(root, 'assets', 'fonts');
const cssDir = path.join(root, 'src', 'styles');

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

const families = [
  { query: 'Baloo+Bhaijaan+2:wght@500;600;700;800', slug: 'baloo', name: 'Baloo Bhaijaan 2' },
  { query: 'IBM+Plex+Sans+Arabic:wght@300;400;500;600;700', slug: 'plex-arabic', name: 'IBM Plex Sans Arabic' },
  { query: 'Fraunces:opsz,wght@9..144,400..700', slug: 'fraunces', name: 'Fraunces' },
];

await fs.mkdir(fontDir, { recursive: true });
await fs.mkdir(cssDir, { recursive: true });

const out = [
  '/* Generated by scripts/fetch-fonts.mjs — local subsets, no network at runtime. */',
  '',
];

for (const family of families) {
  const cssUrl = `https://fonts.googleapis.com/css2?family=${family.query}&display=swap&subset=arabic,latin,latin-ext`;
  const res = await fetch(cssUrl, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`CSS ${family.name}: ${res.status}`);
  const css = await res.text();

  const blockRe = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*@font-face\s*\{([\s\S]*?)\}/g;
  let m;
  let i = 0;
  const seen = new Set();
  while ((m = blockRe.exec(css))) {
    const subset = m[1];
    const body = m[2];
    const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1]?.trim() ?? '400';
    const style = /font-style:\s*([^;]+);/.exec(body)?.[1]?.trim() ?? 'normal';
    const url = /src:\s*url\(([^)]+)\)/.exec(body)?.[1]?.replace(/['"]/g, '');
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1]?.trim();
    if (!url || !range) continue;
    if (subset.includes('vietnamese') || subset.includes('cyrillic') || subset.includes('greek')) continue;

    const key = `${weight}-${style}-${subset}`;
    if (seen.has(key)) continue;
    seen.add(key);
    i += 1;

    const file = `${family.slug}-${weight.replace(/\s+/g, '_')}-${style}-${subset}.woff2`;
    const bin = await fetch(url, { headers: { 'User-Agent': UA } });
    if (!bin.ok) throw new Error(`font ${file}: ${bin.status}`);
    await fs.writeFile(path.join(fontDir, file), Buffer.from(await bin.arrayBuffer()));

    out.push(
      '@font-face {',
      `  font-family: '${family.name}';`,
      `  font-style: ${style};`,
      `  font-weight: ${weight};`,
      '  font-display: swap;',
      `  src: url('../../assets/fonts/${file}') format('woff2');`,
      `  unicode-range: ${range};`,
      '}',
      '',
    );
  }

  console.log(`${family.name}: ${i} files`);
}

await fs.writeFile(path.join(cssDir, 'fonts.css'), out.join('\n'), 'utf8');
console.log('wrote src/styles/fonts.css');
